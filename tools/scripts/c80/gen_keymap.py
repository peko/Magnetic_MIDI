"""Generate plugin/src/keymap.rs (matrix index -> HID usage) from the web-driver layout JSON."""
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[2]))

from magmidi.paths import C80_LAYOUT_JSON, ROOT, captures  # noqa: E402
keys = json.load(open(C80_LAYOUT_JSON))["keys"]
rows = []
for k in sorted(keys, key=lambda k: int(k["index"])):
    i, h = int(k["index"]), int(k["hidCode"], 16)
    if h == 0:
        h = 0x0200 + i  # custom key per Wooting PLUGINS.md (prefix >= 0x2)
    rows.append(f"    ({i}, 0x{h:04X}), // {k['name'] or '?'}")
src = (
    "// @generated by tools/scripts/c80/gen_keymap.py from vendor/c80/webdriver/config/keys/QK75EHEARGB.json\n"
    "// (matrix index = row*22+col, HID usage). Keys without a HID usage get 0x0200+index.\n"
    f"pub const KEYMAP: [(u8, u16); {len(rows)}] = [\n" + "\n".join(rows) + "\n];\n"
)
(ROOT / "plugin/src/keymap.rs").write_text(src)
print(f"wrote {len(rows)} keys")
